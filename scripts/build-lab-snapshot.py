#!/usr/bin/env python3
"""Build browser and AI lab catalogs from the same editable registry."""
import argparse
import hashlib
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def read_registry(source):
    if '</script' in source.lower():
        raise ValueError('Lab registry must not contain a closing script tag')
    values = []
    for name in ['STROBOT_LAB_PLATFORMS', 'STROBOT_COURSE_LABS']:
        match = re.search(r'window\.' + name + r'\s*=\s*({[\s\S]*?})\s*;', source)
        if not match:
            raise ValueError('Missing static lab registry: ' + name)
        values.append(json.loads(match.group(1)))
    platforms, courses = values
    offered = set()
    for course, choices in courses.items():
        if not isinstance(choices, list) or not choices or len(choices) != len(set(choices)):
            raise ValueError('Invalid lab choices for ' + course)
        if any(key not in platforms for key in choices):
            raise ValueError('Course refers to an unknown lab: ' + course)
        offered.update(choices)
    if offered != set(platforms):
        raise ValueError('Active lab registry must contain exactly the offered platforms')
    return platforms, courses


def backend_snapshot(platforms, courses):
    fields = ['name', 'mode', 'languages', 'url', 'externalUrl']
    selected = {key: {field: value[field] for field in fields if field in value}
                for key, value in platforms.items()}
    return (
        '// Generated by scripts/build-lab-snapshot.py from frontend/src/data/lab-platforms.js.\n'
        'export const siteLabPlatforms: Record<string, { name: string; mode: string; languages: string; url?: string; externalUrl?: string }> = '
        + json.dumps(selected, ensure_ascii=False, indent=2) + ';\n'
        'export const siteCourseLabs: Readonly<Record<string, readonly string[]>> = '
        + json.dumps(courses, ensure_ascii=False, indent=2) + ';\n'
    )


def guest_snapshot(text, courses):
    block = 'export const COURSE_LAB_KEYS = Object.freeze(' + json.dumps(courses, ensure_ascii=False, indent=2) + ');'
    result, count = re.subn(r'export const COURSE_LAB_KEYS = Object\.freeze\({[\s\S]*?}\);',
                            lambda _: block, text, count=1)
    if count != 1:
        raise ValueError('Guest tutor is missing its static course lab map')
    return result


def workflow_snapshot(platforms):
    helper = ROOT / 'frontend/src/modules/learning/LabPlatformWorkflows.js'
    program = '''
import {pathToFileURL} from 'node:url';
const {getLabWorkflow} = await import(pathToFileURL(process.argv[1]).href);
const fields = ['mode', 'sourceLabel', 'extensions', 'saveSteps', 'reopenSteps'];
const result = Object.fromEntries(JSON.parse(process.argv[2]).map(key => {
    const workflow = getLabWorkflow(key);
    return [key, Object.fromEntries(fields.map(field => [field, workflow[field]]))];
}));
process.stdout.write(JSON.stringify(result));
'''
    result = subprocess.run(['node', '--input-type=module', '-e', program, str(helper), json.dumps(list(platforms))],
                            check=True, capture_output=True, text=True, timeout=10)
    workflows = json.loads(result.stdout)
    for key, value in workflows.items():
        if value['mode'] not in ['files', 'project', 'worksheet']:
            raise ValueError('Invalid save workflow for ' + key)
        if not isinstance(value['sourceLabel'], str) or not 1 <= len(value['sourceLabel']) <= 120:
            raise ValueError('Invalid source label for ' + key)
        for field in ['extensions', 'saveSteps', 'reopenSteps']:
            if not isinstance(value[field], list) or len(value[field]) > 12:
                raise ValueError('Invalid workflow field ' + key + '/' + field)
            if any(not isinstance(item, str) or not item or len(item) > 1600 for item in value[field]):
                raise ValueError('Invalid workflow instructions ' + key + '/' + field)
        if not value['saveSteps'] or not value['reopenSteps']:
            raise ValueError('Missing save/reopen instructions for ' + key)
    return (
        '// Generated by scripts/build-lab-snapshot.py from LabPlatformWorkflows.js.\n'
        'export const siteLabWorkflows: Readonly<Record<string, { mode: string; sourceLabel: string; extensions: readonly string[]; saveSteps: readonly string[]; reopenSteps: readonly string[] }>> = '
        + json.dumps(workflows, ensure_ascii=False, indent=2) + ';\n'
    )


def snapshots(source):
    platforms, courses = read_registry(source)
    version = hashlib.sha256(source.encode()).hexdigest()[:12]
    block = f'<script id="lab-platform-data" data-lab-version="{version}">\n{source.rstrip()}\n</script>'
    page = ROOT / 'frontend/public/course.learning.html'
    html = page.read_text()
    external = '<script src="../src/data/lab-platforms.js"></script>'
    if external in html:
        expected = html.replace(external, block, 1)
    else:
        expected, count = re.subn(r'<script id="lab-platform-data"[^>]*>.*?</script>',
                                  lambda _: block, html, count=1, flags=re.S)
        if count != 1:
            raise ValueError('Learning page is missing its lab registry snapshot')
    guest = ROOT / 'ai-server/tutor-context.mjs'
    return version, [
        (page, expected),
        (ROOT / 'backend/src/modules/ai-gateway/agent/site-lab-catalog.ts', backend_snapshot(platforms, courses)),
        (guest, guest_snapshot(guest.read_text(), courses)),
        (ROOT / 'backend/src/modules/ai-gateway/agent/site-lab-workflows.ts', workflow_snapshot(platforms)),
    ]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = (ROOT / 'frontend/src/data/lab-platforms.js').read_text()
    version, outputs = snapshots(source)
    stale = [str(file.relative_to(ROOT)) for file, expected in outputs if not file.exists() or file.read_text() != expected]
    if args.check:
        if stale:
            raise SystemExit('Lab snapshots are stale: ' + ', '.join(stale) + '; run python3 scripts/build-lab-snapshot.py')
        print(f'Lab snapshots match registry: {version}')
    else:
        for file, expected in outputs:
            file.write_text(expected)
        print(f'Updated browser and AI lab snapshots: {version}')


if __name__ == '__main__':
    main()
