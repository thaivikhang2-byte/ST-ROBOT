// Keep the AI service deployable with ai-server as its standalone root directory.
// Browser generation files are authoritative; the server copy is generated.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { quizCourses } from '../frontend/src/data/quiz.js';

const root = fileURLToPath(new URL('../', import.meta.url));
const source = path.join(root, 'frontend/src/modules/quiz/generation');
const destination = path.join(root, 'ai-server/generation');
const header = '// Generated by scripts/build-practice-engine.mjs; edit the frontend generation source.\n';
const files = ['QuestionEngine.js', 'DifficultyPolicy.js', 'helpers.js', 'templates/arduino.js', 'templates/creative.js', 'templates/robotics.js'];
const outputs = new Map();
for (const file of files) {
    let text = await readFile(path.join(source, file), 'utf8');
    if (file === 'QuestionEngine.js') text = text.replace(/'\.\.\/\.\.\/\.\.\/data\/quiz\.js(?:\?[^']*)?'/, "'./courses.js'");
    text = text.replace(/(from\s+['"]\.[^'"]+)\?[^'"]+(['"])/g, '$1$2');
    outputs.set(path.join(destination, file), header + text);
}
outputs.set(path.join(destination, 'courses.js'), header + `export const quizCourses = ${JSON.stringify(quizCourses, null, 2)};\n`);
outputs.set(path.join(destination, 'package.json'), '{"type":"module","private":true}\n');
let stale = false;
for (const [target, content] of outputs) {
    if (process.argv.includes('--check')) {
        let existing;
        try { existing = await readFile(target, 'utf8'); } catch {}
        if (existing !== content) { console.error('Stale server engine:', path.relative(root, target)); stale = true; }
    } else {
        await mkdir(path.dirname(target), { recursive: true });
        await writeFile(target, content);
    }
}
if (stale) process.exitCode = 1;
else console.log(`${process.argv.includes('--check') ? 'Verified' : 'Built'} self-contained server practice engine (${outputs.size} files)`);
