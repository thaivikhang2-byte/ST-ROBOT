#!/usr/bin/env python3
"""Exercise the movable lesson tutor in Chromium; no service or AI calls."""
import argparse
import json
from playwright.sync_api import sync_playwright, expect

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--base', default='http://127.0.0.1:8000')
parser.add_argument('--chromium', default='/usr/bin/chromium')
args = parser.parse_args()
BASE = args.base.rstrip('/')
FIXTURE = '''<!doctype html><html lang="vi"><head><meta name="viewport" content="width=device-width,initial-scale=1">
<link rel="stylesheet" href="/frontend/src/assets/css/variables.css">
<link rel="stylesheet" href="/frontend/src/assets/css/base.css">
<link rel="stylesheet" href="/frontend/src/assets/css/pages/selfstudy.css">
<link rel="stylesheet" href="/frontend/src/assets/css/floating-tutor.css"></head>
<body class="learning-page"><div class="learning-workspace"><main class="ws">
<section id="lesson" class="ws-content"><button id="background">Bài học</button></section>
<button type="button" id="tutorLauncher" class="floating-tutor-launcher" aria-label="Mở trợ lý AI">AI</button>
<aside id="tutorPanel" class="ws-ai floating-tutor glass-panel" aria-labelledby="tutorTitle" hidden>
<div class="ai-head"><button type="button" id="tutorDragHandle" class="floating-tutor-handle">
<span class="ai-avatar">AI</span><span><span id="tutorTitle" class="floating-tutor-title">Trợ lý AI STEM Robotics</span>
<span class="floating-tutor-subtitle">Hỏi về bài học và thực hành</span></span></button>
<button type="button" id="tutorClose" class="floating-tutor-close" aria-label="Đóng trợ lý">×</button></div>
<div class="tutor-prompts"><button type="button">Giải thích dễ hiểu</button><button type="button">Gợi ý bước tiếp theo</button></div>
<div id="tutorMessages" aria-live="polite"><div class="chat-message">Nội dung trò chuyện hiện tại.</div></div>
<form id="tutorForm"><label for="tutorQuestion">Câu hỏi của bạn</label><textarea id="tutorQuestion" rows="3"></textarea>
<div class="tutor-actions"><button type="submit" id="tutorSend">Gửi câu hỏi</button><button type="button">Trao đổi mới</button></div>
<p class="small" id="tutorStatus" role="status"></p><p class="small">Hãy đối chiếu câu trả lời với giáo trình.</p></form>
</aside></main></div><script type="module">
import {createFloatingTutor} from '/frontend/src/modules/learning/FloatingTutor.js';
window.tutor = createFloatingTutor({panel:document.querySelector('#tutorPanel'),launcher:document.querySelector('#tutorLauncher'),
handle:document.querySelector('#tutorDragHandle'),closeButton:document.querySelector('#tutorClose')});
window.submissions=0;document.querySelector('#tutorForm').addEventListener('submit',e=>{e.preventDefault();window.submissions++});
</script></body></html>'''


def require(value, message):
    if not value:
        raise AssertionError(message)


def geometry(page, selector):
    return page.locator(selector).bounding_box()


def bounded(page, selectors=('#tutorLauncher', '#tutorPanel')):
    page.wait_for_function('''selectors=>selectors.every(selector=>{
        const r=document.querySelector(selector).getBoundingClientRect(),v=visualViewport;
        return r.left>=v.offsetLeft+11 && r.top>=v.offsetTop+11 && r.right<=v.offsetLeft+v.width-11 && r.bottom<=v.offsetTop+v.height-11;
    })''', arg=list(selectors))
    for selector in selectors:
        result = page.locator(selector).evaluate('''e => {
            const r=e.getBoundingClientRect(),v=visualViewport;
            return {left:r.left,top:r.top,right:r.right,bottom:r.bottom,x:v.offsetLeft,y:v.offsetTop,width:v.width,height:v.height};
        }''')
        require(result['left'] >= result['x'] + 11 and result['top'] >= result['y'] + 11,
                f'{selector} crossed the viewport start: {result}')
        require(result['right'] <= result['x'] + result['width'] - 11 and result['bottom'] <= result['y'] + result['height'] - 11,
                f'{selector} crossed the viewport end: {result}')


with sync_playwright() as p:
    browser = p.chromium.launch(executable_path=args.chromium, headless=True, args=['--no-sandbox'])
    context = browser.new_context(viewport={'width': 1440, 'height': 1000})
    context.route(BASE + '/floating-tutor-fixture.html', lambda route: route.fulfill(content_type='text/html', body=FIXTURE))
    page = context.new_page()
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto(BASE + '/floating-tutor-fixture.html')
    page.wait_for_function('window.tutor !== undefined')
    launcher, panel = page.locator('#tutorLauncher'), page.locator('#tutorPanel')
    expect(panel).to_be_hidden()
    require(geometry(page, '#lesson')['width'] == 1440, 'Closed tutor reserved lesson width')
    # A dragged launcher must not open on the click generated by pointerup.
    before = geometry(page, '#tutorLauncher')
    page.mouse.move(before['x'] + 28, before['y'] + 28)
    page.mouse.down()
    page.mouse.move(820, 780, steps=8)
    page.mouse.up()
    expect(panel).to_be_hidden()
    after = geometry(page, '#tutorLauncher')
    require(after['x'] < before['x'] - 200, 'Launcher did not move')
    saved = page.evaluate("localStorage.getItem('strobot.learning.tutor.position.v1')")
    require(saved is not None, 'Dragged position was not saved')
    page.reload()
    page.wait_for_function('window.tutor !== undefined')
    restored = geometry(page, '#tutorLauncher')
    require(abs(restored['x'] - after['x']) < 2 and abs(restored['y'] - after['y']) < 2, 'Reload lost the launcher position')
    launcher.focus()
    launcher.press('Enter')
    expect(panel).to_be_visible()
    expect(launcher).to_have_attribute('aria-expanded', 'true')
    expect(page.locator('#tutorDragHandle')).to_be_focused()
    expect(panel).to_have_attribute('role', 'dialog')
    expect(panel).to_have_attribute('aria-modal', 'false')
    bounded(page)
    # Move the open panel by its handle. Form controls retain normal interactions.
    before = geometry(page, '#tutorPanel')
    handle = geometry(page, '#tutorDragHandle')
    page.mouse.move(handle['x'] + 50, handle['y'] + 20)
    page.mouse.down()
    page.mouse.move(handle['x'] - 90, handle['y'] - 40, steps=8)
    page.mouse.up()
    require(geometry(page, '#tutorPanel')['x'] < before['x'] - 100, 'Dragging the handle did not move the panel')
    bounded(page)
    page.locator('#tutorQuestion').fill('Giữ lại câu hỏi đang soạn.')
    page.locator('#tutorSend').click()
    require(page.evaluate('window.submissions') == 1, 'Widget intercepted form submission')
    page.locator('#background').click()
    expect(panel).to_be_visible()
    page.keyboard.press('Escape')
    expect(panel).to_be_hidden()
    expect(launcher).to_be_focused()
    launcher.press('Enter')
    expect(page.locator('#tutorQuestion')).to_have_value('Giữ lại câu hỏi đang soạn.')
    page.evaluate('''() => {
        const dialog=document.createElement('dialog');dialog.id='modal';
        dialog.innerHTML='<button type="button">Tài liệu</button>';document.body.append(dialog);dialog.showModal();
    }''')
    page.keyboard.press('Escape')
    expect(page.locator('#modal')).not_to_be_visible()
    expect(panel).to_be_visible()
    page.locator('#tutorClose').click()
    before = geometry(page, '#tutorLauncher')
    launcher.press('ArrowLeft')
    require(geometry(page, '#tutorLauncher')['x'] == before['x'] - 10, 'Keyboard movement failed')
    launcher.press('Home')
    bounded(page, ('#tutorLauncher',))
    # Releasing a cancelled drag outside the source must leave no active drag.
    page.evaluate('''() => {
        const icon=document.querySelector('#tutorLauncher');
        icon.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true,pointerId:77,isPrimary:true,button:0,clientX:1400,clientY:960}));
        window.dispatchEvent(new PointerEvent('pointermove',{pointerId:77,clientX:1200,clientY:800}));
        window.dispatchEvent(new PointerEvent('pointercancel',{pointerId:77}));
    }''')
    before = geometry(page, '#tutorLauncher')
    page.evaluate("window.dispatchEvent(new PointerEvent('pointermove',{pointerId:77,clientX:10,clientY:10}))")
    require(geometry(page, '#tutorLauncher') == before, 'Cancelled drag kept moving')
    launcher.press('Enter')
    expect(panel).to_be_visible()
    # Rotate/narrow the viewport while open, then model the reduced visual viewport
    # and offset caused by an on-screen keyboard without changing layout height.
    page.set_viewport_size({'width': 375, 'height': 812})
    bounded(page)
    page.evaluate('''() => {
        const visual=new EventTarget(); Object.assign(visual,{width:375,height:360,offsetLeft:0,offsetTop:120});
        Object.defineProperty(window,'visualViewport',{configurable:true,value:visual});
        window.dispatchEvent(new Event('resize'));
    }''')
    bounded(page)
    require(geometry(page, '#tutorQuestion')['height'] >= 56, 'Keyboard viewport made the question field unusable')
    require(geometry(page, '#tutorMessages')['height'] >= 48, 'Keyboard viewport removed the message area')
    require(page.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'Tutor caused horizontal page overflow')
    page.evaluate('window.tutor.destroy()')
    expect(panel).to_be_hidden()
    launcher.click()
    expect(panel).to_be_hidden()
    require(not errors, 'Browser errors: ' + json.dumps(errors))
    context.close()
    # Storage failures must not prevent opening, moving or closing the tutor.
    context = browser.new_context(viewport={'width': 375, 'height': 812}, has_touch=True, is_mobile=True)
    context.route(BASE + '/floating-tutor-fixture.html', lambda route: route.fulfill(content_type='text/html', body=FIXTURE))
    context.add_init_script("Storage.prototype.getItem=Storage.prototype.setItem=()=>{throw new Error('Storage blocked')}")
    page = context.new_page()
    page.goto(BASE + '/floating-tutor-fixture.html')
    page.wait_for_function('window.tutor !== undefined')
    before = geometry(page, '#tutorLauncher')
    touch = context.new_cdp_session(page)
    touch.send('Input.dispatchTouchEvent', {'type': 'touchStart', 'touchPoints': [{'x': before['x'] + 28, 'y': before['y'] + 28}]})
    touch.send('Input.dispatchTouchEvent', {'type': 'touchMove', 'touchPoints': [{'x': 180, 'y': 550}]})
    touch.send('Input.dispatchTouchEvent', {'type': 'touchEnd', 'touchPoints': []})
    expect(page.locator('#tutorPanel')).to_be_hidden()
    require(geometry(page, '#tutorLauncher')['x'] < before['x'] - 100, 'Touch drag did not move the launcher')
    page.locator('#tutorLauncher').press('Enter')
    bounded(page)
    page.locator('#tutorDragHandle').press('Home')
    page.keyboard.press('Escape')
    expect(page.locator('#tutorPanel')).to_be_hidden()
    context.close()
    browser.close()
print('PASS floating tutor: drag threshold, capture cancellation, persistence, keyboard, dialog focus, intact form, mobile keyboard bounds, storage failure and cleanup')
